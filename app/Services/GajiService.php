    /**
     * Hitung gaji berdasarkan status pegawai (PNS atau PPPK)
     */
    public static function hitungGajiPegawai($pegawai, int $mkg): int
    {
        $isPppk = str_contains(strtoupper($pegawai->jenis_pegawai ?? ''), 'PPPK');
        $namaGolongan = $pegawai->golongan->nama_golongan ?? ($isPppk ? 'IX' : 'III/c');

        if ($isPppk) {
            return self::getGajiPppk($namaGolongan, $mkg);
        }

        return self::getGajiPns($namaGolongan, $mkg);
    }

    /**
     * Cari nilai gaji terdekat yang tidak melebihi MKG yang ditentukan
     */
    protected static function lookupSalaryByMkg(array $steps, int $mkg): int
    {
        ksort($steps);
        $bestSalary = reset($steps);

        foreach ($steps as $yearStep => $salary) {
            if ($mkg >= $yearStep) {
                $bestSalary = $salary;
            } else {
                break;
            }
        }

        return $bestSalary;
    }

    /**
     * Normalisasi string golongan PNS ke bentuk standar 'III/c'
     */
    protected static function normalizeGolonganPns(?string $input): string
    {
        if (!$input) return 'III/c';

        $clean = strtoupper(trim(str_replace(['\\', ' '], ['/', ''], $input)));
        // Hapus keterangan pangkat jika ada
        if (preg_match('/(I{1,3}|IV)\/[A-E]/', $clean, $matches)) {
            return strtolower($matches[0]); // misal: III/c
        }

        return $clean;
    }

    /**
     * Normalisasi string golongan PPPK ke bentuk romawi 'IX'
     */
    protected static function normalizeGolonganPppk(string|int|null $input): string
    {
        if (!$input) return 'IX';

        $str = strtoupper(trim((string)$input));
        $str = str_replace(['GOLONGAN', 'GOL.', 'GOL', ' '], '', $str);

        // Jika angka desimal 1..17
        $romanMap = [
            1 => 'I', 2 => 'II', 3 => 'III', 4 => 'IV', 5 => 'V',
            6 => 'VI', 7 => 'VII', 8 => 'VIII', 9 => 'IX', 10 => 'X',
            11 => 'XI', 12 => 'XII', 13 => 'XIII', 14 => 'XIV', 15 => 'XV',
            16 => 'XVI', 17 => 'XVII'
        ];

        if (is_numeric($str) && isset($romanMap[(int)$str])) {
            return $romanMap[(int)$str];
        }

        return $str;
    }
